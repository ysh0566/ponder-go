package orm

import (
	"fmt"
	"go/format"
	"go/token"
	"slices"
	"strings"

	"github.com/ysh0566/ponder-go/schema"
)

// GenerateStructs emits the data-only structs used by plain ponder codegen.
func GenerateStructs(packageName string, model schema.Schema) ([]byte, error) {
	if !token.IsIdentifier(packageName) {
		return nil, fmt.Errorf("invalid Go package name")
	}
	if err := model.Validate(schema.Multichain); err != nil {
		return nil, err
	}
	var body strings.Builder
	enums, err := generateEnums(&body, model)
	if err != nil {
		return nil, err
	}
	usesBigInt := false
	for _, table := range model.Tables {
		keys := table.Keys()
		fmt.Fprintf(&body, "type %s struct {\n", modelGoName(table.Name))
		for _, c := range table.Columns {
			base, array := strings.CutSuffix(c.Type, "[]")
			typ := enums[base]
			if c.GoCodec != nil {
				typ = c.GoCodec.Type
			}
			if typ != "" {
				if array || (!c.NotNull && !slices.Contains(keys, c.Name)) {
					typ = "*" + typ
				}
			} else {
				switch base {
				case "text", "hex", "address", "uuid", "numeric", "date", "timestamp":
					typ = "string"
				case "bigint":
					usesBigInt = true
					typ = "*big.Int"
				case "int8", "integer", "smallint":
					typ = "int64"
				case "boolean":
					typ = "bool"
				case "real", "doublePrecision":
					typ = "float64"
				case "bytes":
					typ = "[]byte"
				default:
					typ = "any"
				}
			}
			if array {
				typ = "[]" + typ
			}
			fmt.Fprintf(&body, "%s %s `json:%q`\n", modelGoName(c.Name), typ, c.Name)
		}
		body.WriteString("}\n")
	}
	var source strings.Builder
	fmt.Fprintf(&source, "// Code generated by ponder-go codegen; DO NOT EDIT.\npackage %s\n", packageName)
	if len(enums) > 0 {
		source.WriteString("import \"fmt\"\n")
	}
	if usesBigInt {
		source.WriteString("import \"math/big\"\n")
	}
	source.WriteString(body.String())
	return format.Source([]byte(source.String()))
}
