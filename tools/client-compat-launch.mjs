import {verifyClientProvenance,verifyFingerprints} from './client-compat-provenance.mjs';
// Compile the unchanged TypeScript client test, then use ordinary Node (no tsx IPC).
import fs from 'node:fs';import path from 'node:path';import crypto from 'node:crypto';import {createRequire} from 'node:module';import {spawnSync} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'..');
const source=path.join(root,'bridge/client-compat.ts');
const coreRequire=createRequire(path.resolve(root,'../ponder-upstream/packages/core/package.json'));
// Read package metadata only. Do not import the tsx CLI or loader.
const compilerRequire=createRequire(coreRequire.resolve('tsx/package.json'));
const esbuild=compilerRequire('esbuild');
const clientRoot=path.resolve(root,'../ponder-upstream/packages/client');
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const stamp=new Date().toISOString().replaceAll(/[:.]/g,'-')+'-'+process.pid;
const output=path.join(root,'parity/runs/client-ipc-adapted',stamp);fs.mkdirSync(output,{recursive:true});
const buildDirectory=path.join(root,'.parity-build');fs.mkdirSync(buildDirectory,{recursive:true});
const executable=path.join(buildDirectory,'client-compat-'+stamp+'.mjs');
const report={method:'Environment-adapted TypeScript compilation and ordinary Node launch, no tsx CLI/loader',environment_adapted:true,pristine_file:false,source_credit:0,compiler:{name:'esbuild',version:esbuild.version},source:{file:'bridge/client-compat.ts',sha256:hash(fs.readFileSync(source))},complete:false,success:false};
const save=()=>fs.writeFileSync(path.join(output,'result.json'),JSON.stringify(report,null,2)+'\n');save();
try {
 report.original_client=verifyClientProvenance(root);
 if(process.env.NODE_OPTIONS)throw Error('Client adapter refuses inherited NODE_OPTIONS');
 if(fs.statfsSync(root).bavail*fs.statfsSync(root).bsize<5*1024**3)throw Error('Less than 5 GiB free');
 const url=new URL(process.argv[2]??'');if(url.protocol!=='http:'||url.hostname!=='127.0.0.1')throw Error('Explicit test loopback HTTP endpoint required');
 if(!['account','account_nested'].includes(process.argv[3]))throw Error('Original relation required');
 const dynamicRequire=createRequire(path.join(clientRoot,'package.json'));
 const dynamicDependency=dynamicRequire.resolve('drizzle-orm/pg-core');
 const resolutions=[{specifier:'drizzle-orm/pg-core',kind:'runtime-createRequire',resolved:dynamicDependency,sha256:hash(fs.readFileSync(dynamicDependency))}];
 const compiled=await esbuild.build({entryPoints:[source],absWorkingDir:root,bundle:true,platform:'node',format:'esm',target:'node22',outfile:executable,write:false,metafile:true,plugins:[{
  name:'pinned-client-dependencies',setup(build){build.onResolve({filter:/^(drizzle-orm|eventsource|superjson)(\/|$)/},async args=>{
   if(args.pluginData?.resolving)return;
   const resolved=await build.resolve(args.path,{kind:args.kind,resolveDir:clientRoot,pluginData:{resolving:true}});
   if(resolved.errors.length)return {errors:resolved.errors};
   resolutions.push({specifier:args.path,kind:args.kind,resolved:resolved.path,sha256:hash(fs.readFileSync(resolved.path))});
   return {path:resolved.path,external:true};
  });}
 }]});
 const inputs=Object.keys(compiled.metafile.inputs).map(file=>({file,sha256:hash(fs.readFileSync(path.resolve(root,file)))}));
 report.inputs=inputs;report.dependency_resolutions=resolutions;
 fs.writeFileSync(executable,compiled.outputFiles[0].contents);
 report.compiled_sha256=hash(compiled.outputFiles[0].contents);report.command=[process.execPath,executable,...process.argv.slice(2)];save();
 fs.writeFileSync(path.join(output,'metafile.json'),JSON.stringify(compiled.metafile,null,2)+'\n');
 // Retain the generated bytes as evidence, but remove the executable cache on exit.
 fs.writeFileSync(path.join(output,'compiled.mjs.txt'),compiled.outputFiles[0].contents);
 const result=spawnSync(process.execPath,[executable,...process.argv.slice(2)],{cwd:root,env:process.env,encoding:'utf8'});
 fs.writeFileSync(path.join(output,'stdout.txt'),result.stdout??'');fs.writeFileSync(path.join(output,'stderr.txt'),result.stderr??'');
 report.exit_code=result.status;report.signal=result.signal;report.error=result.error?.message;
 process.stdout.write(result.stdout??'');process.stderr.write(result.stderr??'');
 report.success=result.status===0;
 verifyFingerprints(inputs.map(input=>({file:path.resolve(root,input.file),sha256:input.sha256})));
 verifyFingerprints(resolutions.map(entry=>({file:entry.resolved,sha256:entry.sha256})));
 verifyClientProvenance(root);
 report.inputs_and_dependencies_unchanged=true;
 if(!report.success)process.exitCode=1;
}catch(error){report.error={message:error.message,stack:error.stack};report.success=false;process.exitCode=1;}
finally{esbuild.stop();fs.rmSync(executable,{force:true});report.complete=true;report.finished_utc=new Date().toISOString();save();console.log(JSON.stringify({client_startup_evidence:path.relative(root,output),environment_adapted:true,success:report.success}));}
