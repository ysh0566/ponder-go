// Exact inputs and complete expected snapshot of runtime/index.test.ts:753.
// The pinned file's global chain hooks are platform-blocked; this Go port is
// not a claim that the pristine source file has executed on this environment.
func TestSourceEventOrderOriginal(t *testing.T) {
	t.Run("mergeAsyncGeneratorsWithEventOrder()", func(t *testing.T) {
		// Original promises p1/p3 then p4/p2 all resolve before drain begins.
		p1 := sourceMergeBatch(1, []uint64{1, 7}, 10, [2]float64{1, 7})
		p3 := sourceMergeBatch(2, []uint64{2, 5}, 6, [2]float64{2, 5})
		p4 := sourceMergeBatch(2, []uint64{8, 11}, 20, [2]float64{8, 11})
		p2 := sourceMergeBatch(1, []uint64{8, 13}, 20, [2]float64{8, 13})
		expected := [][]SourceEventGroup{
			{
				{ChainID: 1, Events: []protocol.Object{sourceMergeSnapshotEvent(1, 1)}, Checkpoint: sourceMergeSnapshotCheckpoint(1), BlockRange: [2]float64{1, 1}},
				{ChainID: 2, Events: []protocol.Object{sourceMergeSnapshotEvent(2, 2), sourceMergeSnapshotEvent(5, 2)}, Checkpoint: sourceMergeSnapshotCheckpoint(6), BlockRange: [2]float64{2, 5}},
			},
			{
				{ChainID: 1, Events: []protocol.Object{sourceMergeSnapshotEvent(7, 1)}, Checkpoint: sourceMergeSnapshotCheckpoint(10), BlockRange: [2]float64{1, 7}},
				{ChainID: 2, Events: []protocol.Object{sourceMergeSnapshotEvent(8, 2)}, Checkpoint: sourceMergeSnapshotCheckpoint(8), BlockRange: [2]float64{8, 8}},
			},
			{
				{ChainID: 1, Events: []protocol.Object{sourceMergeSnapshotEvent(8, 1), sourceMergeSnapshotEvent(13, 1)}, Checkpoint: sourceMergeSnapshotCheckpoint(20), BlockRange: [2]float64{8, 13}},
				{ChainID: 2, Events: []protocol.Object{sourceMergeSnapshotEvent(11, 2)}, Checkpoint: sourceMergeSnapshotCheckpoint(20), BlockRange: [2]float64{8, 11}},
			},
		}
		got := [][]SourceEventGroup{}
		for value, err := range MergeSourceEventsWithEventOrder(context.Background(), []SourceEventGenerator{sourceMergeSequence(p1, p2), sourceMergeSequence(p3, p4)}) {
			if err != nil {
				t.Fatal(err)
			}
			got = append(got, value)
		}
		if !reflect.DeepEqual(got, expected) {
			t.Fatalf("complete original snapshot mismatch\ngot: %#v\nwant: %#v", got, expected)
		}
	})
}

// Supplemental lifecycle/ownership cases. They add no original test credit.
func TestSourceEventOrderControls(t *testing.T) {
	t.Run("lazy_initial_heads_concurrent_next_before_yield_and_identity", func(t *testing.T) {
		batch := sourceMergeBatch(7, []uint64{1}, 1, [2]float64{0, 1})
		originalEvent := batch.Events[0]
		first := make(chan SourceEventStep, 1)
		second := make(chan SourceEventStep, 1)
		pendingNext := make(chan SourceEventStep, 1)
		calls := []int{}
		nextCount := 0
		generators := []SourceEventGenerator{
			{Next: func(context.Context) <-chan SourceEventStep {
				calls = append(calls, 0)
				nextCount++
				if nextCount == 1 {
					return first
				}
				return pendingNext
			}},
			{Next: func(context.Context) <-chan SourceEventStep {
				calls = append(calls, 1)
				first <- SourceEventStep{Batch: batch}
				second <- SourceEventStep{Done: true}
				return second
			}},
		}
		sequence := MergeSourceEventsWithEventOrder(context.Background(), generators)
		if len(calls) != 0 {
			t.Fatal("merge must be lazy")
		}
		count := 0
		sequence(func(groups []SourceEventGroup, err error) bool {
			if err != nil {
				t.Fatal(err)
			}
			count++
			if !reflect.DeepEqual(calls, []int{0, 1, 0}) {
				t.Fatalf("initial heads must start before awaiting; next before yield: %v", calls)
			}
			if len(batch.Events) != 0 {
				t.Fatal("owned input batch events must be replaced before yield")
			}
			if reflect.ValueOf(groups[0].Events[0]).Pointer() != reflect.ValueOf(originalEvent).Pointer() {
				t.Fatal("event identity changed")
			}
			groups[0].Events[0]["consumerMutation"] = true
			if originalEvent["consumerMutation"] != true {
				t.Fatal("event must remain original map")
			}
			return false // pending next must not be awaited or child closed by helper.
		})
		if count != 1 {
			t.Fatal(count)
		}
		pendingNext <- SourceEventStep{Done: true}
	})
	t.Run("equal_boundary_advances_first_generator_only", func(t *testing.T) {
		calls := []int{}
		makeGenerator := func(index int) SourceEventGenerator {
			nextCount := 0
			return SourceEventGenerator{Next: func(context.Context) <-chan SourceEventStep {
				calls = append(calls, index)
				nextCount++
				result := make(chan SourceEventStep, 1)
				if nextCount == 1 {
					result <- SourceEventStep{Batch: sourceMergeBatch(uint64(index+1), []uint64{1}, 2, [2]float64{0, 2})}
				} else {
					result <- SourceEventStep{Done: true}
				}
				return result
			}}
		}
		yields := 0
		for groups, err := range MergeSourceEventsWithEventOrder(context.Background(), []SourceEventGenerator{makeGenerator(0), makeGenerator(1)}) {
			if err != nil {
				t.Fatal(err)
			}
			yields++
			if len(groups) != 2 || !reflect.DeepEqual(calls, []int{0, 1, 0}) {
				t.Fatalf("equal-boundary prefetch mismatch: %v", calls)
			}
		}
		if yields != 1 || !reflect.DeepEqual(calls, []int{0, 1, 0, 1}) {
			t.Fatal(yields, calls)
		}
	})
	t.Run("empty_batches_do_not_emit_groups", func(t *testing.T) {
		empty := sourceMergeBatch(1, nil, 1, [2]float64{0, 1})
		full := sourceMergeBatch(1, []uint64{2}, 2, [2]float64{2, 2})
		count := 0
		for groups, err := range MergeSourceEventsWithEventOrder(context.Background(), []SourceEventGenerator{sourceMergeSequence(empty, full)}) {
			if err != nil {
				t.Fatal(err)
			}
			count++
			if len(groups) != 1 || groups[0].Events[0]["checkpoint"] != sourceMergeCheckpoint(2) {
				t.Fatal(groups)
			}
		}
		if count != 1 {
			t.Fatal(count)
		}
	})
	t.Run("initial_failure_does_not_wait_for_other_head", func(t *testing.T) {
		sentinel := errors.New("original provider error")
		unresolved := make(chan SourceEventStep, 1)
		failure := make(chan SourceEventStep, 1)
		failure <- SourceEventStep{Err: sentinel}
		generators := []SourceEventGenerator{{Next: func(context.Context) <-chan SourceEventStep { return unresolved }}, {Next: func(context.Context) <-chan SourceEventStep { return failure }}}
		count := 0
		for _, err := range MergeSourceEventsWithEventOrder(context.Background(), generators) {
			count++
			if err != sentinel {
				t.Fatal("error identity changed", err)
			}
		}
		if count != 1 {
			t.Fatal(count)
		}
	})
	t.Run("empty_generator_list", func(t *testing.T) {
		for _, err := range MergeSourceEventsWithEventOrder(context.Background(), nil) {
			t.Fatal("unexpected yield", err)
		}
	})
	t.Run("cancellation_while_waiting", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		generator := SourceEventGenerator{Next: func(context.Context) <-chan SourceEventStep { cancel(); return make(chan SourceEventStep, 1) }}
		count := 0
		for _, err := range MergeSourceEventsWithEventOrder(ctx, []SourceEventGenerator{generator}) {
			count++
			if !errors.Is(err, context.Canceled) {
				t.Fatal(err)
			}
		}
		if count != 1 {
			t.Fatal(count)
		}
	})
	t.Run("split_preserves_event_identity_and_original_lower_bound", func(t *testing.T) {
		first := sourceMergeBatch(1, []uint64{1, 3}, 4, [2]float64{0, 4})
		second := sourceMergeBatch(2, []uint64{2}, 2, [2]float64{1, 2})
		originals := append([]protocol.Object{}, first.Events...)
		got := [][]SourceEventGroup{}
		for groups, err := range MergeSourceEventsWithEventOrder(context.Background(), []SourceEventGenerator{sourceMergeSequence(first), sourceMergeSequence(second)}) {
			if err != nil {
				t.Fatal(err)
			}
			got = append(got, groups)
		}
		if len(got) != 2 || got[0][0].BlockRange != [2]float64{0, 1} || got[1][0].BlockRange != [2]float64{0, 4} {
			t.Fatal(got)
		}
		for i, group := range []SourceEventGroup{got[0][0], got[1][0]} {
			if reflect.ValueOf(group.Events[0]).Pointer() != reflect.ValueOf(originals[i]).Pointer() {
				t.Fatal("partition copied event")
			}
		}
	})
}
