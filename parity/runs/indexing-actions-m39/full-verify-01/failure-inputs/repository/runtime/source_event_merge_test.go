func sourceMergeCheckpoint(i uint64) string {
	return checkpoint.MustEncode(checkpoint.Checkpoint{BlockTimestamp: i, BlockNumber: i})
}
func sourceMergeEvent(i, chain uint64) protocol.Object {
	return protocol.Object{"checkpoint": sourceMergeCheckpoint(i), "chain": protocol.Object{"id": chain}}
}
func sourceMergeBatch(chain uint64, numbers []uint64, cursor uint64, span [2]float64) *SourceEventBatch {
	events := []protocol.Object{}
	for _, n := range numbers {
		events = append(events, sourceMergeEvent(n, chain))
	}
	return &SourceEventBatch{Events: events, Checkpoint: sourceMergeCheckpoint(cursor), BlockRange: span}
}
func sourceMergeSequence(batches ...*SourceEventBatch) SourceEventGenerator {
	position := 0
	return SourceEventGenerator{Next: func(context.Context) <-chan SourceEventStep {
		result := make(chan SourceEventStep, 1)
		if position < len(batches) {
			result <- SourceEventStep{Batch: batches[position]}
			position++
		} else {
			result <- SourceEventStep{Done: true}
		}
		close(result)
		return result
	}}
}

