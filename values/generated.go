package values

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"strconv"
	"strings"
)

// GenerateBigIntReplacer generates a typed conversion from a Go type expression
// with BigInt leaves, such as [2]BigInt or struct{ Amount BigInt }. The generated
// result preserves fields and array lengths and infers its leaf type from the callback.
func GenerateBigIntReplacer(packageName, name, shape string) ([]byte, error) {
	if !token.IsIdentifier(packageName) || packageName == "_" || !ast.IsExported(name) || !token.IsIdentifier(name) {
		return nil, fmt.Errorf("invalid Go package or exported conversion name")
	}
	fset := token.NewFileSet()
	expr, err := parser.ParseExprFrom(fset, "shape", shape, 0)
	if err != nil {
		return nil, err
	}
	// The placeholder is also the name of the type parameter in the generated
	// code. Printing the parsed type preserves tags and field names verbatim.
	typeText := func(node ast.Expr) string {
		var text strings.Builder
		format.Node(&text, fset, node)
		return text.String()
	}
	var body strings.Builder
	index := 0
	var emit func(ast.Expr, string, string) error
	emit = func(node ast.Expr, src, dst string) error {
		switch n := node.(type) {
		case *ast.Ident:
			switch n.Name {
			case "BigInt":
				fmt.Fprintf(&body, "if %s == nil { return zero, fmt.Errorf(\"nil BigInt leaf\") }\n%s = replace(new(big.Int).Set(%s))\n", src, dst, src)
			case "string", "bool", "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64", "byte", "rune":
				fmt.Fprintf(&body, "%s = %s\n", dst, src)
			default:
				return fmt.Errorf("unsupported leaf type %q", n.Name)
			}
		case *ast.StructType:
			seen := make(map[string]bool)
			for _, field := range n.Fields.List {
				if len(field.Names) == 0 {
					return fmt.Errorf("embedded fields are unsupported")
				}
				for _, id := range field.Names {
					if seen[id.Name] {
						return fmt.Errorf("duplicate field %q", id.Name)
					}
					seen[id.Name] = true
					if !ast.IsExported(id.Name) {
						return fmt.Errorf("expected an exported field, got %q", id.Name)
					}
					if err := emit(field.Type, src+"."+id.Name, dst+"."+id.Name); err != nil {
						return err
					}
				}
			}
		case *ast.ArrayType:
			if n.Len != nil {
				length, ok := n.Len.(*ast.BasicLit)
				if !ok || length.Kind != token.INT {
					return fmt.Errorf("expected a fixed integer array length")
				}
				if _, err := strconv.ParseUint(length.Value, 0, 31); err != nil {
					return err
				}
			}
			idx := fmt.Sprintf("i%d", index)
			index++
			if n.Len == nil {
				fmt.Fprintf(&body, "if %s != nil {\n%s = make(%s,len(%s))\n", src, dst, typeText(n), src)
			}
			fmt.Fprintf(&body, "for %s := range %s {\n", idx, src)
			start := body.Len()
			if err := emit(n.Elt, src+"["+idx+"]", dst+"["+idx+"]"); err != nil {
				return err
			}
			if body.Len() == start {
				fmt.Fprintf(&body, "_ = %s\n", idx)
			}
			body.WriteString("}\n")
			if n.Len == nil {
				body.WriteString("}\n")
			}
		case *ast.MapType:
			key, ok := n.Key.(*ast.Ident)
			if !ok || key.Name != "string" {
				return fmt.Errorf("expected a string-keyed map")
			}
			idx := fmt.Sprintf("key%d", index)
			index++
			tmp := fmt.Sprintf("item%d", index)
			fmt.Fprintf(&body, "if %s != nil {\n%s = make(%s,len(%s))\nfor %s := range %s {\nvar %s %s\n", src, dst, typeText(n), src, idx, src, tmp, typeText(n.Value))
			if err := emit(n.Value, src+"["+idx+"]", tmp); err != nil {
				return err
			}
			fmt.Fprintf(&body, "%s[%s] = %s\n}\n}\n", dst, idx, tmp)
		default:
			return fmt.Errorf("unsupported Go shape %T", node)
		}
		return nil
	}
	if err := emit(expr, "input", "output"); err != nil {
		return nil, err
	}
	// A type alias allows callers to pass their own structurally identical data.
	src := fmt.Sprintf(`// Code generated by ponder-go codegen; DO NOT EDIT.
package %s

import ("math/big"; "fmt")

type %[2]sShape[BigInt any] = %[3]s

func %[2]s[BigInt any](input %[2]sShape[*big.Int], replace func(*big.Int) BigInt) (%[2]sShape[BigInt],error) {
	var zero,output %[2]sShape[BigInt]
	if replace == nil { return zero, fmt.Errorf("missing big integer replacer") }
	%[4]s
	return output,nil
}
`, packageName, name, typeText(expr), body.String())
	return format.Source([]byte(src))
}
