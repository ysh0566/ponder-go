// The Go CLI launches native Go apps. It does not execute TS config/handler files.
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"os/exec"
	"os/signal"
	"path/filepath"
	"ponder.local/ponder-go/abi"
	"ponder.local/ponder-go/checkpoint"
	"ponder.local/ponder-go/schema"
	"ponder.local/ponder-go/store"
	"strings"
	"syscall"
)

const version = "0.18.2-go.0"

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if e := run(ctx, os.Args[1:], os.Stdout); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
func run(ctx context.Context, args []string, out io.Writer) error {
	if len(args) == 0 || args[0] == "--help" || args[0] == "-h" {
		fmt.Fprintln(out, "ponder-go "+version+" (local port in progress)\n\nImplemented: start, serve, codegen, db list, checkpoint encode/decode\nStart/serve build a native Go app; TS source compatibility remains separate.\nPending: dev reload, db prune, db create-views, complete upstream CLI flag parity.")
		return nil
	}
	switch args[0] {
	case "--version", "-V":
		fmt.Fprintln(out, version)
		return nil
	case "checkpoint":
		if len(args) < 2 {
			return fmt.Errorf("checkpoint encode|decode required")
		}
		if args[1] == "encode" {
			var cp checkpoint.Checkpoint
			if e := json.NewDecoder(os.Stdin).Decode(&cp); e != nil {
				return e
			}
			s, e := checkpoint.Encode(cp)
			if e != nil {
				return e
			}
			fmt.Fprintln(out, s)
			return nil
		}
		if args[1] == "decode" {
			raw, e := io.ReadAll(os.Stdin)
			if e != nil {
				return e
			}
			cp, e := checkpoint.Decode(strings.TrimSpace(string(raw)))
			if e != nil {
				return e
			}
			return json.NewEncoder(out).Encode(cp)
		}
		return fmt.Errorf("unknown checkpoint action")
	case "start", "serve":
		flags := flag.NewFlagSet(args[0], flag.ContinueOnError)
		root := flags.String("root", ".", "Native Go project root")
		app := flags.String("app", ".", "Go app package to build")
		if e := flags.Parse(args[1:]); e != nil {
			return e
		}
		if flags.NArg() > 0 {
			return fmt.Errorf("unexpected arguments")
		}
		directory, e := filepath.Abs(*root)
		if e != nil {
			return e
		}
		buildDir := filepath.Join(directory, ".ponder-go", "bin")
		if e = os.MkdirAll(buildDir, 0755); e != nil {
			return e
		}
		binary := filepath.Join(buildDir, "indexer")
		build := exec.CommandContext(ctx, "go", "build", "-o", binary, *app)
		build.Dir = directory
		build.Stdout = out
		build.Stderr = os.Stderr
		if e = build.Run(); e != nil {
			return e
		}
		command := exec.CommandContext(ctx, binary)
		command.Dir = directory
		command.Env = append(os.Environ(), "PONDER_COMMAND="+args[0])
		command.Stdin = os.Stdin
		command.Stdout = out
		command.Stderr = os.Stderr
		return command.Run()
	case "codegen":
		flags := flag.NewFlagSet("codegen", flag.ContinueOnError)
		input := flags.String("schema", "ponder.schema.json", "Native Go schema JSON")
		output := flags.String("out", "ponder_generated.go", "Output Go model file")
		packageName := flags.String("package", "main", "Go package")
		parameters := flags.String("abi-parameters", "", "ABI parameter JSON for a typed decoder")
		decoderName := flags.String("decoder", "Parameters", "Exported ABI decoder name")
		if e := flags.Parse(args[1:]); e != nil {
			return e
		}
		if !schema.Identifier(*packageName) {
			return fmt.Errorf("invalid package name")
		}
		if *parameters != "" {
			raw, e := os.ReadFile(*parameters)
			if e != nil {
				return e
			}
			var params []abi.Parameter
			if e = json.Unmarshal(raw, &params); e != nil {
				return e
			}
			source, e := abi.GenerateParameters(*packageName, *decoderName, params)
			if e != nil {
				return e
			}
			return os.WriteFile(*output, source, 0644)
		}
		raw, e := os.ReadFile(*input)
		if e != nil {
			return e
		}
		var model schema.Schema
		if e = json.Unmarshal(raw, &model); e != nil {
			return e
		}
		if e = model.Validate(schema.Multichain); e != nil {
			return e
		}
		var source strings.Builder
		fmt.Fprintf(&source, "// Code generated by ponder-go codegen; DO NOT EDIT.\npackage %s\n", *packageName)
		big := false
		for _, t := range model.Tables {
			for _, c := range t.Columns {
				big = big || c.Type == "bigint" || c.Type == "bigint[]"
			}
		}
		if big {
			source.WriteString("import \"math/big\"\n")
		}
		for _, t := range model.Tables {
			fmt.Fprintf(&source, "type %s struct {\n", goName(t.Name))
			for _, c := range t.Columns {
				typ := "any"
				switch strings.TrimSuffix(c.Type, "[]") {
				case "text", "hex", "address", "uuid", "numeric", "date", "timestamp":
					typ = "string"
				case "bigint":
					typ = "*big.Int"
				case "int8", "integer", "smallint":
					typ = "int64"
				case "boolean":
					typ = "bool"
				case "real", "doublePrecision":
					typ = "float64"
				case "bytes":
					typ = "[]byte"
				}
				if strings.HasSuffix(c.Type, "[]") {
					typ = "[]" + typ
				}
				fmt.Fprintf(&source, "%s %s `json:\"%s\"`\n", goName(c.Name), typ, c.Name)
			}
			source.WriteString("}\n")
		}
		formatted, e := format.Source([]byte(source.String()))
		if e != nil {
			return e
		}
		if e = os.WriteFile(*output, formatted, 0644); e != nil {
			return e
		}
		fmt.Fprintln(out, *output)
		return nil
	case "db":
		if len(args) < 2 || args[1] != "list" {
			return fmt.Errorf("db prune/create-views are not implemented; see parity/feature-ledger.json")
		}
		flags := flag.NewFlagSet("db list", flag.ContinueOnError)
		url := flags.String("database-url", "", "Explicit task database URL (no environment fallback)")
		if e := flags.Parse(args[2:]); e != nil {
			return e
		}
		if *url == "" {
			return fmt.Errorf("--database-url is required")
		}
		backend, e := store.OpenPostgres(ctx, *url)
		if e != nil {
			return e
		}
		defer backend.Close()
		r, e := backend.Query(ctx, "SELECT n.nspname AS schema FROM pg_namespace n JOIN pg_class c ON c.relnamespace=n.oid WHERE c.relname='_ponder_go_meta' AND n.nspname LIKE 'ponder_go_%' ORDER BY n.nspname")
		if e != nil {
			return e
		}
		return json.NewEncoder(out).Encode(r)
	case "dev":
		return fmt.Errorf("development reloading and automatic shadow rebuild are not implemented yet")
	default:
		return fmt.Errorf("unknown command %q", args[0])
	}
}
func goName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' })
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}
