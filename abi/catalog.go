// UnqualifiedFunctionName represents a compact function name in a dynamic ABI.
// The name includes the empty argument list even when the function takes inputs.
type UnqualifiedFunctionName struct{ base string }

func NewUnqualifiedFunctionName(base string) UnqualifiedFunctionName {
	return UnqualifiedFunctionName{base}
}
func (n UnqualifiedFunctionName) String() string { return n.base + "()" }

// UnqualifiedName formats the name when only the item's own declaration is known.
func (e Event) UnqualifiedName() string { return e.Name }
func (f Function) UnqualifiedName() UnqualifiedFunctionName {
	return NewUnqualifiedFunctionName(f.Name)
}

// FunctionSafeName formats the source callback name in the context of this ABI.
func (a ABI) FunctionSafeName(item Function) string {
	return item.SafeName(a.functionNameCounts[item.Name] > 1)
}

// FindFunctionSafe resolves the same compact names used to register callbacks.
func (a ABI) FindFunctionSafe(name string) (Function, bool) {
	for _, item := range a.functionEntries {
		if a.FunctionSafeName(item) == name {
			return item, true
		}
	}
	return Function{}, false
}

type catalogEntry struct {
	index         int
	name, compact string
	definition    string
	parameters    []string
}

// GenerateCatalog derives event and function types, their compact names and
// type-preserving conversions from a concrete contract ABI.
func GenerateCatalog(packageName string, data []byte) ([]byte, error) {
	if !strings.HasPrefix(strings.TrimSpace(string(data)), "[") {
		return nil, fmt.Errorf("ABI catalog requires a JSON array")
	}
	parsed, err := Parse(string(data))
	if err != nil {
		return nil, err
	}
	return generateCatalog(packageName, data, parsed.eventEntries, parsed.functionEntries, nil)
}

// GenerateEventCatalog describes a source-level event before custom Solidity
// types are resolved to wire types. It can be used to declare factory paths.
func GenerateEventCatalog(packageName string, event Event) ([]byte, error) {
	if event.Type != "event" || event.Name == "" {
		return nil, fmt.Errorf("a named ABI event is required")
	}
	data, err := json.Marshal([]Event{event})
	if err != nil {
		return nil, err
	}
	return generateCatalog(packageName, data, []Event{event}, nil, nil)
}

func generateCatalog(packageName string, data []byte, eventEntries []Event, functionEntries []Function, merged []json.RawMessage) ([]byte, error) {
	if !token.IsIdentifier(packageName) || packageName == "_" {
		return nil, fmt.Errorf("invalid ABI catalog package %q", packageName)
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by ponder-go codegen; DO NOT EDIT.\npackage %s\nimport (\"encoding/json\";\"github.com/ysh0566/ponder-go/abi\")\n", packageName)
	out.WriteString("// Declaration is an ABI item that can be included in a typed contract configuration.\ntype Declaration interface{ json.Marshaler; isABIDeclaration() }\n")
	fmt.Fprintf(&out, "type ContractABI struct{}\nfunc (ContractABI) MarshalJSON() ([]byte,error){return []byte(%q),nil}\n", data)
	events, functions := catalogFamilies(eventEntries, functionEntries)
	itemTypes := make(map[string]string)
	if err := writeCatalogFamily(&out, "Event", events, itemTypes); err != nil {
		return nil, err
	}
	if err := writeCatalogFamily(&out, "Function", functions, itemTypes); err != nil {
		return nil, err
	}
	if merged != nil {
		if err := writeMergedItems(&out, merged, itemTypes); err != nil {
			return nil, err
		}
	}
	return format.Source([]byte(out.String()))
}

func catalogFamilies(eventEntries []Event, functionEntries []Function) ([]catalogEntry, []catalogEntry) {
	events := make([]catalogEntry, 0, len(eventEntries))
	for i, item := range eventEntries {
		events = append(events, catalogEntry{index: i, name: item.Name, compact: overloadedEventName(item), definition: fmt.Sprintf("%#v", item), parameters: item.FactoryParameterPaths()})
	}
	functions := make([]catalogEntry, 0, len(functionEntries))
	for i, item := range functionEntries {
		functions = append(functions, catalogEntry{index: i, name: item.Name, compact: item.SafeName(true), definition: fmt.Sprintf("%#v", item)})
	}
	return events, functions
}

// NamedItem associates a source-level compact name with its ABI declaration.
type NamedItem[T Event | Function] struct {
	Name string
	Item T
}

// DeclarationItems returns distinct declarations in their original order.
func (a ABI) DeclarationItems() ([]NamedItem[Event], []NamedItem[Function], error) {
	events, functions := catalogFamilies(a.eventEntries, a.functionEntries)
	events, err := distinctCatalogEntries("Event", events)
	if err != nil {
		return nil, nil, err
	}
	functions, err = distinctCatalogEntries("Function", functions)
	if err != nil {
		return nil, nil, err
	}
	return namedItems(events, a.eventEntries), namedItems(functions, a.functionEntries), nil
}

func namedItems[T Event | Function](entries []catalogEntry, items []T) []NamedItem[T] {
	var result []NamedItem[T]
	for _, entry := range entries {
		result = append(result, NamedItem[T]{entry.compact, items[entry.index]})
	}
	return result
}

// DeclarationNames returns the compact names exposed by a concrete ABI's type union.
func (a ABI) DeclarationNames() (events, functions []string, err error) {
	es, fs, err := a.DeclarationItems()
	if err != nil {
		return nil, nil, err
	}
	for _, e := range es {
		events = append(events, e.Name)
	}
	for _, f := range fs {
		functions = append(functions, f.Name)
	}
	return
}

// GoFieldNames removes punctuation. When two different names would map
// to one identifier, encode their exact names in an unambiguous suffix.
func GoFieldNames(values []string) map[string]string {
	result := make(map[string]string)
	counts := make(map[string]int)
	for _, value := range values {
		if _, exists := result[value]; exists {
			continue
		}
		field := GoFieldName(value)
		result[value] = field
		counts[field]++
	}
	for value, field := range result {
		if counts[field] > 1 {
			result[value] = field + "_" + hex.EncodeToString([]byte(value))
		}
	}
	return result
}

func distinctCatalogEntries(kind string, entries []catalogEntry) ([]catalogEntry, error) {
	// A type union contains each distinct declaration once, even if a slice
	// contains the same event or function multiple times.
	unique := make([]catalogEntry, 0, len(entries))
	seen := make(map[string]bool)
	counts := make(map[string]int)
	for _, entry := range entries {
		if !seen[entry.definition] {
			seen[entry.definition] = true
			counts[entry.name]++
			unique = append(unique, entry)
		}
	}
	seen = make(map[string]bool)
	for i := range unique {
		entry := &unique[i]
		if counts[entry.name] == 1 {
			entry.compact = entry.name
			if kind == "Function" {
				entry.compact += "()"
			}
		}
		if seen[entry.compact] {
			return nil, fmt.Errorf("different ABI declarations share compact %s name %q", kind, entry.compact)
		}
		seen[entry.compact] = true
	}
	return unique, nil
}

func writeCatalogFamily(out *strings.Builder, kind string, entries []catalogEntry, itemTypes map[string]string) error {
	unique, err := distinctCatalogEntries(kind, entries)
	if err != nil {
		return err
	}
	var compactNames, baseNames []string
	for _, entry := range unique {
		compactNames = append(compactNames, entry.compact)
		baseNames = append(baseNames, entry.name)
	}
	fields, bases := GoFieldNames(compactNames), GoFieldNames(baseNames)
	var items, names []string
	writtenBase := make(map[string]bool)
	for _, entry := range unique {
		field := fields[entry.compact]
		baseType := "Bare" + kind + bases[entry.name]
		if !writtenBase[entry.name] {
			baseName := entry.name
			if kind == "Function" {
				baseName += "()"
			}
			fmt.Fprintf(out, "type %s struct{}\nfunc (%s) String() string {return %s}\n", baseType, baseType, strconv.Quote(baseName))
			writtenBase[entry.name] = true
		}
		itemType, nameType := kind+"Item"+field, kind+"Name"+field
		itemTypes[entry.definition] = itemType
		items = append(items, itemType)
		names = append(names, nameType)
		fmt.Fprintf(out, "type %s struct{}\ntype %s struct{}\n", itemType, nameType)
		fmt.Fprintf(out, "func (%s) Definition() abi.%s {return %s}\n", itemType, kind, entry.definition)
		fmt.Fprintf(out, "func (%s) isABIDeclaration() {}\nfunc (item %s) MarshalJSON() ([]byte,error) {return json.Marshal(item.Definition())}\n", itemType, itemType)
		fmt.Fprintf(out, "func (%s) CompactName() %s {return %s{}}\n", itemType, nameType, nameType)
		fmt.Fprintf(out, "func (%s) UnqualifiedName() %s {return %s{}}\n", itemType, baseType, baseType)
		fmt.Fprintf(out, "func (%s) String() string {return %s}\n", nameType, strconv.Quote(entry.compact))
		fmt.Fprintf(out, "func (%s) Item() %s {return %s{}}\n", nameType, itemType, itemType)
		fmt.Fprintf(out, "func (n %s) MarshalText() ([]byte,error){return []byte(n.String()),nil}\n", nameType)
		if len(entry.parameters) > 0 {
			writeCatalogParameters(out, field, itemType, entry.parameters)
		}
	}
	if len(items) == 0 {
		fmt.Fprintf(out, "type %sItems interface{abi.%s}\n", kind, kind)
		fallback := "string"
		if kind == "Function" {
			fallback = "abi.UnqualifiedFunctionName"
		}
		fmt.Fprintf(out, "type %sNames interface{%s}\n", kind, fallback)
		return nil
	}
	writeCatalogSet(out, kind+"Items", items)
	writeCatalogSet(out, kind+"Names", names)
	fmt.Fprintf(out, "func Format%s[N %sNames,I interface{%sItems;CompactName() N}](item I) N{return item.CompactName()}\n", kind, kind, kind)
	fmt.Fprintf(out, "func Parse%s[I %sItems,N interface{%sNames;Item() I}](name N) I{return name.Item()}\n", kind, kind, kind)
	return nil
}

func writeCatalogSet(out *strings.Builder, name string, types []string) {
	// Go permits at most 100 terms in a constraint union. For larger ABIs,
	// mark each generated type as a member using a package-private method.
	if len(types) <= 100 {
		fmt.Fprintf(out, "type %s interface{%s}\n", name, strings.Join(types, " | "))
		return
	}
	method := "is" + name
	fmt.Fprintf(out, "type %s interface{%s()}\n", name, method)
	for _, typ := range types {
		fmt.Fprintf(out, "func (%s) %s() {}\n", typ, method)
	}
}

// FactoryParameterPaths exposes scalar inputs and named members of first-level tuples.
func (e Event) FactoryParameterPaths() []string {
	var result []string
	seen := make(map[string]bool)
	add := func(path string) {
		if !seen[path] {
			result = append(result, path)
			seen[path] = true
		}
	}
	for _, p := range e.Inputs {
		if p.Name == "" {
			continue
		}
		if p.Components == nil {
			add(p.Name)
			continue
		}
		for _, child := range p.Components {
			if child.Name != "" && child.Components == nil {
				add(p.Name + "." + child.Name)
			}
		}
	}
	return result
}

// Definition lets runtime ABI metadata use the same configuration API as generated events.
func (e Event) Definition() Event { return e }

func writeCatalogParameters(out *strings.Builder, field, itemType string, paths []string) {
	typ := "EventParameter" + field
	set := "EventParameters" + field
	ids := GoFieldNames(paths)
	fmt.Fprintf(out, "type %s struct{path string}\nfunc(p %s) ParameterOf(%s)string{return p.path}\n", typ, typ, itemType)
	fmt.Fprintf(out, "type %s struct{\n", set)
	for _, path := range paths {
		fmt.Fprintf(out, "%s %s\n", ids[path], typ)
	}
	fmt.Fprintf(out, "}\nfunc (%s) Parameters() %s{return %s{\n", itemType, set, set)
	for _, path := range paths {
		fmt.Fprintf(out, "%s:%s{%q},\n", ids[path], typ, path)
	}
	out.WriteString("}}\n")
}
